function fnv1a64(value: string): bigint {
  let hash = FNV1A_64_OFFSET
  for (const byte of new TextEncoder().encode(value)) {
    hash ^= BigInt(byte)
    hash = BigInt.asUintN(64, hash * FNV1A_64_PRIME)
  }
  return hash
}

/** Same opaque id, same readable label, on every surface. */
export function sessionLabelFromId(sessionId: string): string {
  const hash = fnv1a64(sessionId)
  const adjective = SESSION_ADJECTIVES[Number(hash % 64n)]
  const noun = SESSION_NOUNS[Number((hash >> 6n) % 64n)]
  return `${adjective} ${noun}`
}
